/**
 * TYPES: the "shape" of every piece of content on the site.
 *
 * A TypeScript type is like a form with labelled boxes: it says which fields
 * an object must have. If a product file forgets a field or misspells one,
 * `npm run typecheck` (and the editor) point at the mistake before the site
 * is built.
 *
 * How content flows:
 *   src/content/apps/<slug>/*.ts   (the words, written as AppInfo objects)
 *        ↓ imported by src/content/apps/index.ts (the list of products)
 *        ↓ read by the pages in src/app/ and the components in src/components/
 *   HTML pages in out/              (what visitors see)
 *
 * The legal types mirror the apps' own in-app legal screens, so policy text
 * can be copied across section by section.
 */

/** One block of a legal document: a paragraph or a bulleted list. */
export type LegalBlock =
  | { kind: "paragraph"; text: string }
  | { kind: "bullets"; items: string[] };

/** A numbered section, such as "2. Camera, photos and voice". */
export interface LegalSection {
  /** Section title, including its number. */
  heading: string;
  blocks: LegalBlock[];
}

/** A whole legal document (Terms or Privacy Policy). */
export interface LegalDocument {
  title: string;
  /** Date the current wording took effect, e.g. "29 October 2026". */
  effectiveDate: string;
  /** Label shown before the date, as the app words it. Defaults to "Effective date". */
  dateLabel?: string;
  /** Opening paragraph before the sections, if the document has one. */
  intro?: string;
  sections: LegalSection[];
}


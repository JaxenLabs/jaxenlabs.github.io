/** A short feature card on a product page ("Everything you need" section). */
export interface AppFeature {
  title: string;
  text: string;
  icon: IconName;
}

/**
 * A product's Google Play listing, word for word. It lives in
 * `apps/<slug>/store.ts`, which is GENERATED by `npm run update:play`;
 * never edit it by hand.
 */
export interface StoreListing {
  /** Title on Google Play, e.g. "JaxScan: PDF, OCR, Cam Scanner". */
  title: string;
  /** The 80-character short description. */
  shortDescription: string;
  /** Developer name shown on Google Play. */
  developer: string;
  /** Download count as Google Play shows it, e.g. "5K+". Added up for "Total users" on the home page. */
  downloads: string;
  /** Opening paragraphs of the full description. */
  intro: string[];
  /** A heading the listing puts above all its sections, if any. */
  sectionsTitle?: string;
  /** The listing's headed sections, as paragraphs and bullet lists. */
  sections: LegalSection[];
}

/**
 * Everything the site knows about one product. Each product folder's
 * `index.ts` exports one of these, for example:
 *
 *   export const jaxscan: AppInfo = {
 *     slug: "jaxscan",                    // → /jaxscan/
 *     name: "JaxScan",
 *     tagline: store.shortDescription,    // from Google Play
 *     description: store.intro.join(" "),
 *     iconSrc: "/jaxscan/icon.png",       // file in public/jaxscan/
 *     ...
 *   };
 *
 * Fields with "?" are optional.
 */
export interface AppInfo {
  /** URL folder: `/jaxbudget/`. Lowercase, never change once published (links and Google rely on it). */
  slug: string;
  /** Product name as shown on the site, e.g. "JaxBudget". */
  name: string;
  /** One line under the name. Usually the Play short description. */
  tagline: string;
  /** A short paragraph explaining what the product does. Usually the Play intro. */
  description: string;
  /** Path under `public/`, square PNG. */
  iconSrc: string;
  /** Store link, if the app is live. */
  playStoreUrl?: string;
  /** For client work: who it was built for. Client products have no policy pages here. */
  client?: string;
  /** schema.org application category, e.g. "FinanceApplication". */
  category: string;
  /** Extra search words for this app's pages. */
  keywords: string[];
  /** Six short highlight cards for the product page. */
  features: AppFeature[];
  /** The Google Play listing (generated; see StoreListing). */
  store: StoreListing;
  /**
   * Why the app asks for Google user data (shown on the app home page).
   * Google's OAuth review checks that the home page explains this.
   */
  googleDataUse?: { title: string; paragraphs: string[] };
  /** Privacy Policy, for our own products. Without it there is no `/<slug>/privacy-policy/` page. */
  privacy?: LegalDocument;
  /** Terms, if the app has them. Without them there is no `/<slug>/terms/` page. */
  terms?: LegalDocument;
}

/** Shorthand for a paragraph block: `p("Some text.")`. */
export const p = (text: string): LegalBlock => ({ kind: "paragraph", text });

/**
 * Shorthand for a bulleted list block: `ul("First point", "Second point")`.
 * In items and paragraphs, `**text**` is shown in bold (used for labels
 * such as "Location:"), and web links and email addresses become clickable.
 */
export const ul = (...items: string[]): LegalBlock => ({ kind: "bullets", items });
